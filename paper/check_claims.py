#!/usr/bin/env python3
"""Flag quantitative claims in paper/main.tex that are not macros from artifacts.

    python paper/check_claims.py

A claim is a numeric token in the body of main.tex. Allowed:
  * LaTeX macros defined in paper/generated/macros.tex (values synced from
    outputs/*.json, outputs/*.csv, configs/workshop_vicreg.yaml)
  * Horizon index set {1,5,10} matching scripts/render_rollout_comparison.py
  * Filenames / \texttt paths
  * Bibliographic years are in references.bib, not checked here
"""

from __future__ import annotations

import re
import sys
from pathlib import Path

PAPER = Path(__file__).resolve().parent
MAIN = PAPER / "main.tex"
MACROS = PAPER / "generated" / "macros.tex"

# Structural k-set used by evaluate_model / rollout figures, not a measured metric.
ALLOWED_BARE = {
    "1",
    "5",
    "10",  # reported horizons
}

SKIP_ENV = re.compile(
    r"\\(?:includegraphics|input|bibliography|texttt|label|ref|citep|citet|documentclass)"
    r"(?:\[[^\]]*\])?\{[^}]*\}"
    r"|\\begin\{(?:subfigure|minipage)\}\{[^}]*\}"
    r"|Prompt~\d+"
)


def defined_macros(text: str) -> dict[str, str]:
    found = {}
    for match in re.finditer(r"\\newcommand\{\\([A-Za-z]+)\}\{((?:[^{}]|\{[^{}]*\})*)\}", text):
        found[match.group(1)] = match.group(2)
    return found


def strip_skipped(source: str) -> str:
    source = SKIP_ENV.sub(" ", source)
    source = re.sub(r"%.*", " ", source)
    source = re.sub(r"\\(?:subsection|section|paragraph|caption|title)\{", " ", source)
    return source


def main() -> int:
    body = MAIN.read_text(encoding="utf-8")
    macros = defined_macros(MACROS.read_text(encoding="utf-8")) if MACROS.is_file() else {}
    used = set(re.findall(r"\\([A-Za-z]+)(?:\{\})?", body))
    missing_macros = sorted(name for name in used if name[0].isupper() and name not in macros
                            and name not in {"NEpisodes"})  # NEpisodes is in macros
    # Uppercase-leading names that look like our macros.
    our_names = {name for name in used if name in macros}

    leftover = []
    scanned = strip_skipped(body)
    scanned = re.sub(r"\$R\^2\$", " ", scanned)
    scanned = re.sub(r"\\ImgSize\^2", " ", scanned)
    scanned = re.sub(r"\^2", " ", scanned)
    # Remove macro uses so their expansions are not double-counted as literals.
    for name in macros:
        scanned = re.sub(rf"\\{name}\{{\}}?", " ", scanned)
    for match in re.finditer(r"(?<![A-Za-z])(\d+\.\d+|\d+)(?![A-Za-z])", scanned):
        token = match.group(1)
        if token in ALLOWED_BARE:
            continue
        leftover.append(token)

    unique = sorted(set(leftover), key=lambda s: (len(s), s))
    print(f"macros defined: {len(macros)}")
    print(f"artifact macros used in main.tex: {len(our_names)}")
    undefined = sorted(
        name
        for name in used
        if name in {
            # heuristic: CamelCase macros we generate
        }
        or (name[:1].isupper() and name[1:].isalnum() and name not in macros
            and name not in {"NEpisodes", "DumpBackend", "DumpSeed", "DumpWorkers"})
    )
    # simpler undefined check
    generated_style = [n for n in used if re.fullmatch(r"[A-Z][A-Za-z0-9]+", n) and n not in macros]
    # Filter known LaTeX
    latex_caps = {
        "NEpisodes",  # actually is a macro
        "T",
        "E",
        "RGB",
        "GT",
        "JEPA",
        "AC",
        "VICReg",
        "MSE",
        "EMA",
        "GNN",
        "MLS",
        "MPM",
        "SOTA",
        "YAML",
        "Prompt",
        "Table",
        "Figure",
        "Section",
        "Variant",
        "Pixel",
        "AE",
        "CPU",
        "JSON",
        "CSV",
        "HEAD",
        "BYOL",
        "ViT",
        "DPI",
        "GNS",
        "R",
    }
    undefined_macros = [n for n in generated_style if n not in latex_caps]
    undefined_macros = [n for n in undefined_macros if n not in macros]

    print("undefined-looking macros:", ", ".join(undefined_macros) or "(none)")
    print("bare numeric tokens remaining:", ", ".join(unique) or "(none)")
    claims_path = PAPER / "CLAIMS.md"
    lines = [
        "# Quantitative claim self-check",
        "",
        "Generated by `python paper/check_claims.py` after `python paper/sync_tables.py`.",
        "",
        "## Rule",
        "Every measured number in `main.tex` must be a macro from `generated/macros.tex`",
        "(synced from `outputs/*.json`, `outputs/*.csv`, or `configs/workshop_vicreg.yaml`).",
        "Bare `{1,5,10}` tokens are allowed as the eval/figure horizon index set.",
        "",
        f"## Macros used ({len(our_names)})",
        "",
    ]
    for name in sorted(our_names):
        lines.append(f"- `\\{name}` = `{macros.get(name, '?')}`")
    lines.extend(
        [
            "",
            "## Undefined CamelCase control sequences",
            "",
            (", ".join(f"`\\{n}`" for n in undefined_macros) or "_none_"),
            "",
            "## Bare numeric tokens in `main.tex`",
            "",
        ]
    )
    if unique:
        lines.append("**FLAGGED:** " + ", ".join(unique))
        lines.append("")
        lines.append("These did not expand from `generated/macros.tex`. Trace or delete them.")
    else:
        lines.append("None besides the allowed horizon indices {1, 5, 10}.")
    lines.extend(
        [
            "",
            "## Missing / scoped workshop artifacts",
            "",
            "The 3-seed × 4-variant grid (`outputs/ablation_multiseed.json`) was skipped.",
            "Workshop VICReg vs MSE uses `outputs/ablation_twoseed.json` (mean ± half-range",
            "over seeds 42 and 43 — a 2-seed range, not a sample std).",
            "",
        ]
    )
    claims_path.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"wrote {claims_path}")
    if undefined_macros or (set(unique) - ALLOWED_BARE):
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
